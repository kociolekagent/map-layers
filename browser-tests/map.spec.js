import {test,expect} from '@playwright/test';
test.beforeEach(async({page})=>{await page.route('https://tile.openstreetmap.org/**',route=>route.abort());});
test('examples, duplicate details, independent toggles and safe labels',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('./');
 await expect(page.locator('.point-label')).toHaveCount(2);
 const box=await page.locator('#map').boundingBox();
 await page.mouse.click(box.x+box.width/2,box.y+box.height/2);
 await expect(page.locator('#details article')).toHaveCount(2);
 await expect(page.locator('#details')).toContainText('Stanowisko A');
 await expect(page.locator('#details')).toContainText('Stanowisko B');
 await page.getByLabel('Punkty pomiarowe',{exact:true}).check();
 await expect(page.locator('.point-label')).toHaveCount(4);
 await page.getByLabel('Miejsca obserwacji',{exact:true}).uncheck();
 await expect(page.locator('.point-label')).toHaveCount(2);
 await expect(page.locator('#details article')).toHaveCount(0);
 expect(errors).toEqual([]);
});
test('empty and invalid dataset do not break map; retry succeeds',async({page})=>{
 await page.route('**/datasets/miejsca.geojson',r=>r.fulfill({json:{type:'FeatureCollection',features:[]}}));
 await page.route('**/datasets/pomiary.geojson',r=>r.fulfill({json:{type:'FeatureCollection',features:[{}]}}));
 await page.goto('./');
 await expect(page.locator('#datasets')).toContainText('0 punktów');
 await page.getByLabel('Punkty pomiarowe',{exact:true}).check();
 await expect(page.locator('#datasets')).toContainText('Błąd:');
 await expect(page.locator('.point-label')).toHaveCount(0);
 await page.unroute('**/datasets/pomiary.geojson');
 await page.getByLabel('Punkty pomiarowe',{exact:true}).uncheck();
 await page.getByLabel('Punkty pomiarowe',{exact:true}).check();
 await expect(page.locator('.point-label')).toHaveCount(2);
});
test('names are text, not HTML',async({page})=>{
 await page.route('**/datasets/miejsca.geojson',async r=>{const response=await r.fetch();const data=await response.json();data.features[0].properties.name='<b>Punkt</b>';await r.fulfill({json:data});});
 await page.goto('./');await expect(page.locator('.point-label').first()).toHaveText('<b>Punkt</b>');
 await expect(page.locator('.point-label b')).toHaveCount(0);
});
test('multipoint measurement, undo, finish, resume and existing details',async({page})=>{
 await page.goto('./');await expect(page.locator('.point-label')).toHaveCount(2);
 const box=await page.locator('#map').boundingBox();
 const click=()=>page.mouse.click(box.x+box.width/2,box.y+box.height/2);
 await page.getByRole('button',{name:'Mierz odległość',exact:true}).click();
 await click();await expect(page.locator('#measure-result')).toContainText('drugie miejsce');
 await expect(page.locator('#details article')).toHaveCount(0);
 await click();await expect(page.locator('#measure-result')).toContainText('Łącznie: 0 m');
 await page.mouse.click(box.x+box.width/2+100,box.y+box.height/2+100);
 await expect(page.locator('#measure-result')).toContainText('Punkty: 3');
 await page.getByRole('button',{name:'Cofnij punkt',exact:true}).click();
 await expect(page.locator('#measure-result')).toContainText('Łącznie: 0 m');
 await page.getByRole('button',{name:'Zakończ',exact:true}).click();
 await click();await expect(page.locator('#measure-result')).toContainText('Punkty: 2');
 await expect(page.locator('#details article')).toHaveCount(2);
 await page.getByRole('button',{name:'Wznów',exact:true}).click();
 await click();await expect(page.locator('#measure-result')).toContainText('Punkty: 3');
 await page.getByLabel('Miejsca obserwacji',{exact:true}).uncheck();
 await expect(page.locator('#measure-result')).toContainText('Łącznie: 0 m');
 await page.getByRole('button',{name:'Wyczyść',exact:true}).click();
 await click();await page.mouse.click(box.x+box.width/2+100,box.y+box.height/2+100);
 await expect(page.locator('#measure-result')).toContainText('Łącznie:');
 await expect(page.locator('#measure-result')).not.toContainText('Łącznie: 0 m');
 await page.keyboard.press('Escape');
 await expect(page.locator('#measure-toggle')).toHaveAttribute('aria-pressed','false');
 await page.getByLabel('Miejsca obserwacji',{exact:true}).check();await click();
 await expect(page.locator('#details article')).toHaveCount(2);
});
test('local editor CRUD, search, map refresh and persistence',async({page})=>{
 await page.goto('./');await expect(page.getByRole('button',{name:'Utwórz zestaw',exact:true})).toBeVisible();
 await page.getByLabel('Nazwa nowego zestawu',{exact:true}).fill('Lokalny');
 await page.getByRole('button',{name:'Utwórz zestaw',exact:true}).click();
 await expect(page.locator('#editor')).toContainText('Zapisano lokalnie.');
 await page.getByLabel('Zestaw do edycji',{exact:true}).selectOption({label:'Lokalny (0)'});
 await page.getByRole('button',{name:'Dodaj punkt',exact:true}).click();
 await page.getByLabel('Nazwa punktu',{exact:true}).fill('Nowy lokalny');
 await page.getByLabel('Długość geograficzna',{exact:true}).fill('21.0122');
 await page.getByLabel('Szerokość geograficzna',{exact:true}).fill('52.2297');
 await page.getByLabel('Opis punktu',{exact:true}).fill('Opis lokalny');
 await page.getByRole('button',{name:'Zapisz punkt',exact:true}).click();
 await expect(page.locator('.point-label')).toHaveCount(3);
 await page.getByLabel('Szukaj punktów',{exact:true}).fill('lokalny');
 await expect(page.locator('.editor-results article')).toHaveCount(1);
 await page.getByRole('button',{name:'Pokaż',exact:true}).click();
 await expect(page.locator('#details article')).toHaveCount(3);
 await page.getByRole('button',{name:'Edytuj',exact:true}).click();
 await page.getByLabel('Nazwa punktu',{exact:true}).fill('Zmieniony');
 await page.getByRole('button',{name:'Zapisz punkt',exact:true}).click();
 await expect(page.locator('#details')).toContainText('Zmieniony');
 await page.getByLabel('Nazwa zestawu',{exact:true}).fill('Lokalny po zmianie');
 await page.getByRole('button',{name:'Zmień nazwę zestawu',exact:true}).click();
 await expect(page.getByLabel('Lokalny po zmianie',{exact:true})).toBeVisible();
 await page.reload();await expect(page.getByLabel('Lokalny po zmianie',{exact:true})).toBeVisible();
 await expect(page.locator('.point-label')).toHaveCount(3);
 await page.getByLabel('Zestaw do edycji',{exact:true}).selectOption({label:'Lokalny po zmianie (1)'});
 page.once('dialog',d=>d.dismiss());await page.getByRole('button',{name:'Usuń punkt',exact:true}).click();
 await expect(page.locator('.point-label')).toHaveCount(3);
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Usuń punkt',exact:true}).click();
 await expect(page.locator('.point-label')).toHaveCount(2);
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'Usuń zestaw',exact:true}).click();
 await expect(page.getByLabel('Lokalny po zmianie',{exact:true})).toHaveCount(0);
});
test('unavailable IndexedDB falls back to read-only source map',async({page})=>{
 await page.addInitScript(()=>Object.defineProperty(window,'indexedDB',{get(){throw new Error('Storage denied')}}));
 await page.goto('./');await expect(page.locator('#editor')).toContainText('Edycja niedostępna');
 await expect(page.locator('.point-label')).toHaveCount(2);
 await expect(page.getByRole('button',{name:'Utwórz zestaw',exact:true})).toHaveCount(0);
});
test('failed writes do not claim success or change the map',async({page})=>{
 await page.goto('./');await expect(page.getByLabel('Nazwa zestawu',{exact:true})).toBeVisible();
 await page.evaluate(()=>{IDBObjectStore.prototype.put=function(){throw new DOMException('Quota exhausted','QuotaExceededError')}});
 await page.getByLabel('Nazwa zestawu',{exact:true}).fill('Nie zapisano');
 await page.getByRole('button',{name:'Zmień nazwę zestawu',exact:true}).click();
 await expect(page.locator('#editor')).toContainText('Nie zapisano:');
 await expect(page.getByLabel('Miejsca obserwacji',{exact:true})).toBeVisible();
 await expect(page.locator('#editor')).not.toContainText('Zapisano lokalnie.');
});
